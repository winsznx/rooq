// Generates typed `as const` ABI modules for viem from Foundry artifacts.
// Run after `forge build`: node scripts/gen-abi.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const contracts = [
  ["ClearingHouse", "perps/ClearingHouse.sol"],
  ["MarginVault", "perps/MarginVault.sol"],
  ["MarketBackstop", "perps/MarketBackstop.sol"],
  ["PerpLens", "perps/PerpLens.sol"],
  ["MarketRegistry", "market/MarketRegistry.sol"],
  ["MarketPreflight", "market/MarketPreflight.sol"],
  ["OracleAdapter", "oracle/OracleAdapter.sol"],
  ["MockPriceFeed", "oracle/MockPriceFeed.sol"],
  ["SpotFactory", "spot/SpotFactory.sol"],
  ["SpotPool", "spot/SpotPool.sol"],
  ["SpotRouter", "spot/SpotRouter.sol"],
  ["MockERC20", "tokens/MockERC20.sol"],
];

const outDir = join(root, "packages/sdk/src/abi");
mkdirSync(outDir, { recursive: true });
const index = [];
const manifest = {};
for (const [name, src] of contracts) {
  const file = join(root, "contracts/out", src.split("/").pop(), `${name}.json`);
  const artifact = JSON.parse(readFileSync(file, "utf8"));
  const abi = JSON.stringify(artifact.abi, null, 2);
  const runtime = artifact.deployedBytecode?.object ?? "";
  manifest[name] = {
    source: `contracts/src/${src}`,
    runtimeBytecodeSha256: createHash("sha256").update(runtime).digest("hex"),
    runtimeBytes: (runtime.length - 2) / 2,
  };
  const varName = `${name[0].toLowerCase()}${name.slice(1)}Abi`;
  writeFileSync(join(outDir, `${name}.ts`), `// Generated by scripts/gen-abi.mjs from contracts/out. Do not edit.\nexport const ${varName} = ${abi} as const;\n`);
  index.push(`export { ${varName} } from "./${name}";`);
}
writeFileSync(join(outDir, "index.ts"), `${index.join("\n")}\n`);
writeFileSync(join(root, "packages/sdk/abi-manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
console.log(`wrote ${contracts.length} ABI modules`);
